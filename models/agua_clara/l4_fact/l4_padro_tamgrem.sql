    NULLIF(TRIM(raw."SECCIO"), '') AS SECCIO,
    NULLIF(TRIM(raw."EPIGRAF_IAE"), '') AS EPIGRAF_IAE,
    TRY_TO_DECIMAL(NULLIF(TRIM(raw."PERC_BONIF_TAMGREM"), ''), 5, 2) AS PERC_BONIF_TAMGREM,
    TRY_TO_DECIMAL(NULLIF(TRIM(raw."IMP_CUOTA"), ''), 11, 2) AS IMP_CUOTA,

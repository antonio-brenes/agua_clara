    NULLIF(TRIM(raw."ID_LIMIT"), '') AS ID_LIMIT,
    NULLIF(TRIM(raw."SUBTIP_TAXA_TAMGREM"), '') AS SUBTIP_TAXA_TAMGREM,
    NULLIF(TRIM(raw."OBSERVACIONS"), '') AS OBSERVACIONS,
    TRY_TO_TIMESTAMP_NTZ(NULLIF(TRIM(raw."TS_ALTA"), '')) AS TS_ALTA,

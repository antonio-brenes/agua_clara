count_issues AS (

    SELECT
        'COUNT_MISMATCH' AS CONTROL_TYPE,
        'ERROR' AS SEVERITY,
        OBJECT_NAME,
        RAW_MODEL,
        L4_MODEL,
        CAST(NULL AS VARCHAR) AS BUSINESS_KEY,
        RAW_COUNT AS VALUE_RAW,
        L4_COUNT AS VALUE_L4,
        L4_COUNT - RAW_COUNT AS DIFFERENCE,
        'El numero total de filas difiere entre RAW y L4' AS DETAIL
    FROM row_counts
    WHERE RAW_COUNT <> L4_COUNT

),

invalid_raw_keys AS (

    SELECT
        'INVALID_RAW_KEY' AS CONTROL_TYPE,
        'ERROR' AS SEVERITY,
        OBJECT_NAME,
        RAW_MODEL,
        L4_MODEL,
        CAST(NULL AS VARCHAR) AS BUSINESS_KEY,
        COUNT(*) AS VALUE_RAW,
        0 AS VALUE_L4,
        -COUNT(*) AS DIFFERENCE,
        'Filas RAW con clave natural nula, vacia o no convertible al tipo L4' AS DETAIL
    FROM raw_key_rows
    WHERE NOT IS_VALID_KEY
    GROUP BY OBJECT_NAME, RAW_MODEL, L4_MODEL

),

raw_duplicate_keys AS (

    SELECT
        'DUPLICATE_RAW_KEY' AS CONTROL_TYPE,
        'ERROR' AS SEVERITY,
        OBJECT_NAME,
        RAW_MODEL,
        L4_MODEL,
        BUSINESS_KEY,
        COUNT(*) AS VALUE_RAW,
        1 AS VALUE_L4,
        1 - COUNT(*) AS DIFFERENCE,
        'Clave natural repetida en RAW' AS DETAIL
    FROM raw_key_rows
    WHERE IS_VALID_KEY
    GROUP BY OBJECT_NAME, RAW_MODEL, L4_MODEL, BUSINESS_KEY
    HAVING COUNT(*) > 1

),

l4_duplicate_keys AS (

    SELECT
        'DUPLICATE_L4_KEY' AS CONTROL_TYPE,
        'ERROR' AS SEVERITY,
        OBJECT_NAME,
        RAW_MODEL,
        L4_MODEL,
        BUSINESS_KEY,
        1 AS VALUE_RAW,
        COUNT(*) AS VALUE_L4,
        COUNT(*) - 1 AS DIFFERENCE,
        'Clave natural repetida en L4' AS DETAIL
    FROM l4_key_rows
    GROUP BY OBJECT_NAME, RAW_MODEL, L4_MODEL, BUSINESS_KEY
    HAVING COUNT(*) > 1

),

missing_in_l4 AS (

    SELECT
        'MISSING_IN_L4' AS CONTROL_TYPE,
        'ERROR' AS SEVERITY,
        r.OBJECT_NAME,
        r.RAW_MODEL,
        r.L4_MODEL,
        r.BUSINESS_KEY,
        1 AS VALUE_RAW,
        0 AS VALUE_L4,
        -1 AS DIFFERENCE,

    LEFT JOIN raw_valid_keys AS r
        ON r.OBJECT_NAME = l.OBJECT_NAME
       AND r.BUSINESS_KEY = l.BUSINESS_KEY
    WHERE r.BUSINESS_KEY IS NULL

)


    UNION ALL

SELECT 'CONVENI_FRAU' AS OBJECT_NAME, 'edw_h_conveni_frau' AS SILVER_MODEL, 'l4_conveni_frau' AS L4_MODEL, HK_CONVENI_FRAU AS HASH_KEY FROM {{ ref('edw_h_conveni_frau') }}

    UNION ALL

SELECT 'HIST_SS_PE' AS OBJECT_NAME, 'edw_h_hist_ss_pe' AS SILVER_MODEL, 'l4_hist_ss_pe' AS L4_MODEL, HK_HIST_SS_PE AS HASH_KEY FROM {{ ref('edw_h_hist_ss_pe') }}

    UNION ALL


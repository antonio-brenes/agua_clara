/*
   Reconciliación L4 -> SILVER_EDW para Hubs.

   Devuelve únicamente incidencias:
   - COUNT_MISMATCH: diferencia de volumetría.
   - MISSING_IN_SILVER: clave esperada en L4 que no existe en el Hub.
   - UNEXPECTED_IN_SILVER: clave presente en el Hub que ya no aparece en la imagen actual L4.

   UNEXPECTED_IN_SILVER se clasifica como WARN porque los Hubs son append-only y
   pueden conservar claves históricas que ya no estén presentes en la imagen actual de L4.

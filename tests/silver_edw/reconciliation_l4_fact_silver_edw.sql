),

expected_distinct AS (

    SELECT DISTINCT
        OBJECT_NAME,
        SILVER_MODEL,
        L4_MODEL,
        HASH_KEY,
        BUSINESS_KEY
    FROM expected_keys

),

actual_distinct AS (

    SELECT DISTINCT
        OBJECT_NAME,
        SILVER_MODEL,
        L4_MODEL,
        HASH_KEY
    FROM actual_keys

),

counts AS (

    SELECT
        COALESCE(e.OBJECT_NAME, a.OBJECT_NAME) AS OBJECT_NAME,
        COALESCE(e.SILVER_MODEL, a.SILVER_MODEL) AS SILVER_MODEL,
        COALESCE(e.L4_MODEL, a.L4_MODEL) AS L4_MODEL,
        COALESCE(e.L4_COUNT, 0) AS L4_COUNT,
        COALESCE(a.SILVER_COUNT, 0) AS SILVER_COUNT
    FROM (
        SELECT OBJECT_NAME, SILVER_MODEL, L4_MODEL, COUNT(*) AS L4_COUNT
        FROM expected_distinct
        GROUP BY OBJECT_NAME, SILVER_MODEL, L4_MODEL
    ) AS e
    FULL OUTER JOIN (
        SELECT OBJECT_NAME, SILVER_MODEL, L4_MODEL, COUNT(*) AS SILVER_COUNT
        FROM actual_distinct
        GROUP BY OBJECT_NAME, SILVER_MODEL, L4_MODEL
    ) AS a
        ON a.OBJECT_NAME = e.OBJECT_NAME

),

count_issues AS (

    SELECT
        'COUNT_MISMATCH' AS CONTROL_TYPE,
        'ERROR' AS SEVERITY,
        OBJECT_NAME,
        SILVER_MODEL,
        L4_MODEL,
        CAST(NULL AS VARCHAR) AS HASH_KEY,
        CAST(NULL AS VARCHAR) AS BUSINESS_KEY,
        L4_COUNT,
        SILVER_COUNT,
        SILVER_COUNT - L4_COUNT AS COUNT_DIFFERENCE,
        'KO' AS RECONCILIATION_STATUS
    FROM counts
    WHERE SILVER_COUNT <> L4_COUNT

),

missing_in_silver AS (

    SELECT
        'MISSING_IN_SILVER' AS CONTROL_TYPE,
        'ERROR' AS SEVERITY,
        e.OBJECT_NAME,
        e.SILVER_MODEL,
        e.L4_MODEL,
        e.HASH_KEY,
        e.BUSINESS_KEY,
        CAST(NULL AS NUMBER) AS L4_COUNT,
        CAST(NULL AS NUMBER) AS SILVER_COUNT,
        CAST(NULL AS NUMBER) AS COUNT_DIFFERENCE,
        'KO' AS RECONCILIATION_STATUS
    FROM expected_distinct AS e
    LEFT JOIN actual_distinct AS a
        ON a.OBJECT_NAME = e.OBJECT_NAME
       AND a.HASH_KEY = e.HASH_KEY
    WHERE a.HASH_KEY IS NULL

),

unexpected_in_silver AS (

    SELECT
        'UNEXPECTED_IN_SILVER' AS CONTROL_TYPE,
        'WARN' AS SEVERITY,
        a.OBJECT_NAME,
        a.SILVER_MODEL,
        a.L4_MODEL,
        a.HASH_KEY,
        CAST(NULL AS VARCHAR) AS BUSINESS_KEY,
        CAST(NULL AS NUMBER) AS L4_COUNT,
        CAST(NULL AS NUMBER) AS SILVER_COUNT,
        CAST(NULL AS NUMBER) AS COUNT_DIFFERENCE,
        'WARN' AS RECONCILIATION_STATUS
    FROM actual_distinct AS a
    LEFT JOIN expected_distinct AS e
        ON e.OBJECT_NAME = a.OBJECT_NAME
       AND e.HASH_KEY = a.HASH_KEY
    WHERE e.HASH_KEY IS NULL

)

SELECT * FROM count_issues
UNION ALL
SELECT * FROM missing_in_silver
UNION ALL
SELECT * FROM unexpected_in_silver

    UNION ALL

SELECT 'DTE_MUNICIPAL' AS OBJECT_NAME, 'edw_h_dte_municipal' AS SILVER_MODEL, 'l4_dte_municipal' AS L4_MODEL, HK_DTE_MUNICIPAL AS HASH_KEY FROM {{ ref('edw_h_dte_municipal') }}

    UNION ALL

SELECT 'TARIFA_FACTURACIO' AS OBJECT_NAME, 'edw_h_tarifa_facturacio' AS SILVER_MODEL, 'l4_tarifa_facturacio' AS L4_MODEL, HK_TARIFA_FACTURACIO AS HASH_KEY FROM {{ ref('edw_h_tarifa_facturacio') }}

    UNION ALL

